/**
 * 사용 가능한 카테고리 목록 리턴 함수
 */
export function getCategories() {
  return wordCategories.map((c) => c.category);
}

/**
 * 무작위로 하나의 카테고리와 단어를 뽑아주는 헬퍼 함수
 * (targetCategory가 제공되면 해당 주제 내에서 선출, 없거나 ALL이면 전체 무작위)
 */
export function getRandomWord(targetCategory) {
  let categoryObj;
  if (targetCategory && targetCategory !== "ALL") {
    categoryObj = wordCategories.find((c) => c.category === targetCategory);
  }
  if (!categoryObj) {
    categoryObj = wordCategories[Math.floor(Math.random() * wordCategories.length)];
  }
  const word = categoryObj.words[Math.floor(Math.random() * categoryObj.words.length)];
  return {
    category: categoryObj.category,
    word: word,
  };
}
